static uint64_t kat_hmac(const uint8_t *key, size_t key_n,
                         const uint8_t *message, size_t n,
                         const uint8_t expected256[32], const uint8_t expected512[64])
{
    uint8_t a[32], b[64];
    moo_krypto_hmac_sha256(key, key_n, message, n, a);
    crypto_sha512_hmac(b, key, key_n, message, n);
    return (uint64_t)equal_bytes(a, expected256, sizeof(a)) |
           ((uint64_t)equal_bytes(b, expected512, sizeof(b)) << 1);
}

