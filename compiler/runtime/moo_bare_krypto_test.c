static bool kat_ed25519_case(const uint8_t seed_vector[32], const uint8_t expected_public[32],
                             const uint8_t expected_sig[64], const uint8_t *message, size_t n)
{
    uint8_t seed[32], secret[64], public_key[32], sig[64];
    memcpy(seed, seed_vector, sizeof(seed));
    crypto_ed25519_key_pair(secret, public_key, seed);
    crypto_ed25519_sign(sig, secret, message, n);
    bool ok = equal_bytes(public_key, expected_public, sizeof(public_key)) &&
              equal_bytes(sig, expected_sig, sizeof(sig)) &&
              crypto_ed25519_check(sig, public_key, message, n) == 0;
    sig[0] ^= 1;
    ok = crypto_ed25519_check(sig, public_key, message, n) != 0 && ok;
    crypto_wipe(secret, sizeof(secret));
    return ok;
}

