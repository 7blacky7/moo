static bool kat_aead(void)
{
    const uint8_t message[] = "Ladies and Gentlemen of the class of '99: If I could offer you only "
                              "one tip for the future, sunscreen would be it.";
    _Static_assert(sizeof(message) - 1 == sizeof(aead_ciphertext), "RFC 8439 message size");
    uint8_t ct[sizeof(aead_ciphertext)], decoded[sizeof(aead_ciphertext)], tag[sizeof(aead_tag)];
    moo_krypto_chacha20_poly1305_encrypt(aead_key, aead_nonce, aead_aad, sizeof(aead_aad),
                                        message, sizeof(ct), ct, tag);
    bool ok = equal_bytes(ct, aead_ciphertext, sizeof(ct)) &&
              equal_bytes(tag, aead_tag, sizeof(tag)) &&
              moo_krypto_chacha20_poly1305_decrypt(aead_key, aead_nonce, aead_aad, sizeof(aead_aad),
                                                  ct, sizeof(ct), tag, decoded) == 0 &&
              equal_bytes(decoded, message, sizeof(decoded));
    tag[0] ^= 1;
    memset(decoded, 0xa5, sizeof(decoded));
    bool rejected = moo_krypto_chacha20_poly1305_decrypt(aead_key, aead_nonce, aead_aad, sizeof(aead_aad),
                                                        ct, sizeof(ct), tag, decoded) == -1;
    for (size_t i = 0; i < sizeof(decoded); i++)
        rejected = (decoded[i] == 0xa5) && rejected;
    return ok && rejected;
}

